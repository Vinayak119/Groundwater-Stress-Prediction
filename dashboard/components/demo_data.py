_SEASONS = ["Pre-monsoon", "Monsoon", "Post-monsoon", "Rabi"]
_AQUIFER_TYPES = ["Crystalline Hard-Rock", "Alluvial", "Sedimentary"]


def get_demo_wells(include_candidates: bool = True) -> pd.DataFrame:
    """
    Return synthetic groundwater observation wells centered on the agreed research scope.

    Primary Focus: Tamil Nadu (Core training baseline).
    Candidate Hold-Outs: Karnataka or Andhra Pradesh (unconfirmed candidate states).

    Columns:
    - well_id (synthetic)
    - state
    - district (synthetic label)
    - latitude, longitude (synthetic coordinates within regional bounding box)
    - aquifer_type
    - mean_depth_mbgl (Strictly depth below ground in metres)
    - dataset_role (Primary Baseline vs Candidate Hold-Out)
    """
    rows = []
    well_num = 1

    states_to_include = list(_STATE_CONFIG.keys()) if include_candidates else ["Tamil Nadu"]

    for state in states_to_include:
        cfg = _STATE_CONFIG[state]
        districts = cfg["demo_districts"]
        for i in range(cfg["n_demo_wells"]):
            lat = cfg["lat_c"] + RNG.normal(0, 0.6)
            lon = cfg["lon_c"] + RNG.normal(0, 0.6)
            depth = max(1.5, round(RNG.normal(cfg["depth_mean"], cfg["depth_std"]), 2))
            aquifer = RNG.choice(_AQUIFER_TYPES, p=[0.70, 0.20, 0.10])
            dist = districts[i % len(districts)]
            prefix = "TN" if state == "Tamil Nadu" else ("KA" if state == "Karnataka" else "AP")

            rows.append({
                "well_id":          f"DEMO-{prefix}-{well_num:03d}",
                "state":            state,
                "district":         dist,
                "latitude":         round(lat, 4),
                "longitude":        round(lon, 4),
                "aquifer_type":     aquifer,
                "mean_depth_mbgl":  depth,
                "measurement_unit": "MBGL",
                "n_observations":   int(RNG.integers(12, 40)),
                "trend_mbgl_yr":    round(cfg["trend"] + RNG.normal(0, 0.03), 3),
                "dataset_role":     "Primary Dataset (Core)" if state == "Tamil Nadu" else "Candidate Hold-Out (Unconfirmed)",
            })
            well_num += 1

    df = pd.DataFrame(rows)
    df["stress_category_demo"] = pd.cut(
        df["mean_depth_mbgl"],
        bins=[0, 8, 15, 25, 999],
        labels=["Low Stress (Demo)", "Moderate Stress (Demo)", "High Stress (Demo)", "Critical Stress (Demo)"],
    )
    return df


def get_demo_observations(well_id: str = "DEMO-TN-001", start_year: int = 1991, end_year: int = 2025) -> pd.DataFrame:
    """
    Generate synthetic quarterly groundwater observations for a well across 1991–2025.

    Splits the timeline into:
    - 1991–2020: Primary Historical Dataset (Core training & evaluation).
    - 2021–2025: Additional Newer-Period Dataset (Conditional temporal validation).

    Measurement unit: MBGL (Metres Below Ground Level — depth to water).
    """
    dates, levels, seasons, rainfalls, partitions = [], [], [], [], []
    base_level = 8.5
    trend_per_year = 0.08

    for yr in range(start_year, end_year + 1):
        partition_label = "Primary Historical (1991–2020)" if yr <= 2020 else "Conditional Recent (2021–2025)"
        for q, (season, monsoon_boost) in enumerate(
            [("Pre-monsoon", -1.2), ("Monsoon", 2.2), ("Post-monsoon", 1.1), ("Rabi", -0.4)]
        ):
            level = base_level + trend_per_year * (yr - start_year) - monsoon_boost + RNG.normal(0, 0.35)
            level = max(1.2, round(level, 2))

            rain = max(0.0, RNG.normal(
                {"Pre-monsoon": 35.0, "Monsoon": 240.0, "Post-monsoon": 180.0, "Rabi": 25.0}[season], 20.0
            ))
            dates.append(pd.Timestamp(f"{yr}-{(q * 3 + 1):02d}-01"))
            levels.append(level)
            seasons.append(season)
            rainfalls.append(round(rain, 1))
            partitions.append(partition_label)

    return pd.DataFrame({
        "date":               dates,
        "well_id":            well_id,
        "season":             seasons,
        "water_level_mbgl":   levels,
        "measurement_unit":   "MBGL",
        "rainfall_mm":        rainfalls,
        "timeline_partition": partitions,
    })


def get_demo_dataset() -> pd.DataFrame:
    """
    Return a synthetic tabular dataset conforming to the agreed research scope.

    Includes:
    - Tamil Nadu (1991–2020): Primary training matrix.
    - Tamil Nadu (2021–2025): Conditional recent validation slice.
    - Candidate Hold-Out states (Karnataka, Andhra Pradesh): For geographic generalisation testing.
    """
    wells = get_demo_wells(include_candidates=True)
    all_rows = []

    for _, well in wells.iterrows():
        # Candidate holdout wells simulate 1991-2020 series; TN wells simulate 1991-2025 series
        end_yr = 2025 if well["state"] == "Tamil Nadu" else 2020
        obs = get_demo_observations(well["well_id"], start_year=1991, end_year=end_yr)
        for _, row in obs.iterrows():
            all_rows.append({
                "well_id":            well["well_id"],
                "state":              well["state"],
                "district":           well["district"],
                "latitude":           well["latitude"],
                "longitude":          well["longitude"],
                "aquifer_type":       well["aquifer_type"],
                "year":               row["date"].year,
                "month":              row["date"].month,
                "season":             row["season"],
                "water_level_mbgl":   row["water_level_mbgl"],
                "measurement_unit":   "MBGL",
                "rainfall_mm":        row["rainfall_mm"],
                "dataset_role":       well["dataset_role"],
                "timeline_partition": row["timeline_partition"],
            })

    df = pd.DataFrame(all_rows)
    df = df.sort_values(["well_id", "year", "month"]).reset_index(drop=True)

    # Feature engineering simulation (strictly lag t-1, t-2 with no future leakage)
    df["wl_lag_1"] = df.groupby("well_id")["water_level_mbgl"].shift(1)
    df["wl_lag_2"] = df.groupby("well_id")["water_level_mbgl"].shift(2)
    df["wl_roll_4_mean"] = (
        df.groupby("well_id")["water_level_mbgl"]
        .transform(
            lambda s: s.shift(1).rolling(4, min_periods=1).mean()
        )
    )
    df["target_wl_next"] = df.groupby("well_id")["water_level_mbgl"].shift(-1)
    return df


