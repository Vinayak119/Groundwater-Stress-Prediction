def get_demo_shap_importances() -> pd.DataFrame:
    """Return synthetic SHAP feature importances for UI layout testing."""
    features = [
        "wl_lag_1", "wl_lag_2", "wl_roll_4_mean", "rainfall_mm",
        "month_sin", "month_cos", "latitude", "longitude",
        "aquifer_type", "year",
    ]
    importances = [0.38, 0.22, 0.14, 0.09, 0.05, 0.04, 0.03, 0.02, 0.02, 0.01]
    std_vals = [v * RNG.uniform(0.1, 0.25) for v in importances]
    return pd.DataFrame({
        "feature":   features,
        "mean_shap": importances,
        "std_shap":  [round(s, 4) for s in std_vals],
    }).sort_values("mean_shap", ascending=False).reset_index(drop=True)


def get_demo_shap_waterfall(n_features: int = 10) -> pd.DataFrame:
    """Return synthetic SHAP waterfall values for single-prediction UI preview."""
    features = get_demo_shap_importances()["feature"].tolist()[:n_features]
    vals = RNG.uniform(-2.2, 2.2, size=n_features)
    vals[0] = 1.95  # lag-1 strongly positive
    vals[1] = 1.10
    vals[2] = -0.75
    return pd.DataFrame({"feature": features, "shap_value": [round(v, 3) for v in vals]})


def get_demo_state_summary() -> pd.DataFrame:
    """Return synthetic summary table comparing primary vs candidate states."""
    wells = get_demo_wells(include_candidates=True)
    summary = (
        wells.groupby(["state", "dataset_role"])
        .agg(
            n_demo_wells=("well_id", "count"),
            mean_depth_mbgl=("mean_depth_mbgl", "mean"),
            max_depth_mbgl=("mean_depth_mbgl", "max"),
            trend_mbgl_yr=("trend_mbgl_yr", "mean"),
        )
        .round(2)
        .reset_index()
    )
    return summary
